
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const outputFile = path.join(__dirname, 'labs.js');
const screenshotsDir = path.join(__dirname, 'public', 'screenshots');

const labFolders = [
    { id: '01', folder: 'Lab-01', title: 'Node.js Basics', type: 'script' },
   { id: '02', folder: 'Lab-02', title: 'HTTP Server', type: 'server' },
{ id: '03', folder: 'Lab-03', title: 'Student Directory', type: 'server' },
{ id: '04', folder: 'Lab-04', title: 'Advanced Server', type: 'server' },
    { id: '05', folder: 'Lab-05', title: 'Asynchronous Node.js', type: 'script' },
    { id: '06', folder: 'Lab-06', title: 'File System & CLI Notes', type: 'script' },
    { id: '07', folder: 'Lab-07', title: 'EventEmitter', type: 'script' }
];

const labs = labFolders.map((lab) => {
    const folderPath = path.join(rootDir, lab.folder);

    if (!fs.existsSync(folderPath)) {
        console.warn(`Skipped: ${lab.folder} folder not found`);
        return null;
    }

    const files = fs.readdirSync(folderPath)
        .filter(file => file.endsWith('.js'))
        .sort();

    const screenshots = fs.existsSync(screenshotsDir)
        ? fs.readdirSync(screenshotsDir)
            .filter(file =>
                /\.(png|jpe?g)$/i.test(file) &&
                file.toLowerCase().startsWith(`lab-${Number(lab.id)}-`)
            )
            .sort()
        : [];

    return {
        id: lab.id,
        title: lab.title,
        topic: lab.title,
        type: lab.type,
        folder: lab.folder,
        files,
        screenshots
    };
}).filter(Boolean);

const content = `// Automatically generated by build-labs.js
module.exports = ${JSON.stringify(labs, null, 2)};
`;

fs.writeFileSync(outputFile, content, 'utf8');

console.log('\nLab registry generated successfully!');
console.log(`Labs discovered: ${labs.length}`);

labs.forEach(lab => {
    console.log(
        `Lab ${lab.id}: ${lab.title} ` +
        `(${lab.files.length} JavaScript files, ` +
        `${lab.screenshots.length} screenshots)`
    );
});

console.log(`\nOutput: ${outputFile}`);
